import type { Question, QuestionType, Difficulty, SubjectId } from './types'

// ── Builder ────────────────────────────────────────────────────────────────
// Keeps the seed bank readable: id, skill and topic are derived, and a
// multiple-choice question only needs its options, answer index and reasoning.
type Extra = Partial<Pick<Question, 'accepted' | 'source' | 'year'>>

function q(
  subjectId: SubjectId,
  skillId: string,
  difficulty: Difficulty,
  text: string,
  options: string[],
  correct: number,
  explanation: string,
  marks = 2,
  extra?: Extra,
): Question {
  return {
    id: `${skillId.toLowerCase()}-${text.length}-${text.slice(0, 8).replace(/\W/g, '')}`,
    subjectId,
    topicId: '',
    skillId,
    type: 'mcq',
    difficulty,
    text,
    options,
    correct,
    accepted: [],
    explanation,
    marks,
    ...extra,
  }
}

function tf(
  subjectId: SubjectId,
  skillId: string,
  difficulty: Difficulty,
  text: string,
  isTrue: boolean,
  explanation: string,
  marks = 2,
): Question {
  return {
    id: `${skillId.toLowerCase()}-${text.length}-tf`,
    subjectId,
    topicId: '',
    skillId,
    type: 'true-false',
    difficulty,
    text,
    options: ['True', 'False'],
    correct: isTrue ? 0 : 1,
    accepted: [],
    explanation,
    marks,
  }
}

function short(
  subjectId: SubjectId,
  skillId: string,
  difficulty: Difficulty,
  text: string,
  accepted: string[],
  explanation: string,
  marks = 2,
): Question {
  return {
    id: `${skillId.toLowerCase()}-${text.length}-sa`,
    subjectId,
    topicId: '',
    skillId,
    type: 'short',
    difficulty,
    text,
    options: [],
    correct: -1,
    accepted,
    explanation,
    marks,
  }
}

